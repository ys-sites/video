/** 做同款 for a community game: an original game built from a detailed brief (goal, controls, rules, art, assets, acceptance), never a copy. */
export function communityRemixPrompt(game: GameCard) {
  const brief = (communityBriefs as Record<string, unknown>)[game.id.replace(/^community-/, '')];
  const lead = `Make an original game in the spirit of "${game.title}". Use original characters, names, story and art; do not copy its code or assets.`;
  return brief ? `${lead}\nFollow this brief, including every acceptance check:\n${JSON.stringify(brief, null, 2)}` : `${lead} ${game.description}`;
}

/** Agent instructions are returned once at creation; keep them so a draft or failed game can be handed over again. */
const instructionKey = 'om-game-instructions';
export function rememberInstruction(id: string, instruction: string) {
  try { const all = JSON.parse(localStorage.getItem(instructionKey) || '{}'); all[id] = instruction; localStorage.setItem(instructionKey, JSON.stringify(all)); } catch { /* storage may be unavailable */ }
}
export function storedInstruction(id: string): string | null {
  try { return JSON.parse(localStorage.getItem(instructionKey) || '{}')[id] ?? null; } catch { return null; }
}

