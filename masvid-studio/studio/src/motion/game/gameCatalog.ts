/** The brief sent to the Agent: chosen options first, then the user's words. */
export function composeBrief({ prompt, genre, style, setting, multiplayer }: GameBrief) {
  const parts = [style && `${styleLabels[style]} style`, multiplayer && 'with multiplayer', genre && genreLabels[genre], setting && `${settingLabels[setting]} setting`].filter(Boolean);
  return [parts.join(', '), prompt.trim()].filter(Boolean).join('. ');
}

